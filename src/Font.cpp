static const unsigned char* glyphFor(char c) {
    unsigned char uc = (unsigned char)c;
    if (uc >= 'a' && uc <= 'z') uc = (unsigned char)std::toupper(uc); // map lowercase
    if (uc < 32 || uc > 95) uc = '?' ;  // fallback for unsupported
    return GLYPHS[uc - 32];
}

int textWidth(const std::string& s, int scale) {
    if (s.empty()) return 0;
    return (int)s.size() * (GLYPH_W + 1) * scale - scale; // no trailing gap
}

static void drawRaw(SDL_Renderer* r, const std::string& s, int x, int y,
                    int scale, SDL_Color c) {
    SDL_SetRenderDrawColor(r, c.r, c.g, c.b, c.a);
    int penX = x;
    for (char ch : s) {
        const unsigned char* g = glyphFor(ch);
        for (int row = 0; row < GLYPH_H; ++row) {
            unsigned char bits = g[row];
            for (int col = 0; col < GLYPH_W; ++col) {
                if (bits & (1 << (GLYPH_W - 1 - col))) {
                    SDL_Rect px{ penX + col * scale, y + row * scale, scale, scale };
                    SDL_RenderFillRect(r, &px);
                }
            }
        }
        penX += (GLYPH_W + 1) * scale;
    }
}

static int alignedX(const std::string& s, int x, int scale, Align a) {
    if (a == Align::Left)   return x;
    int w = textWidth(s, scale);
    if (a == Align::Center) return x - w / 2;
    return x - w; // Right
}

void draw(SDL_Renderer* r, const std::string& s, int x, int y,
          int scale, SDL_Color color, Align align) {
    drawRaw(r, s, alignedX(s, x, scale, align), y, scale, color);
}

void drawShadowed(SDL_Renderer* r, const std::string& s, int x, int y,
                  int scale, SDL_Color color, Align align) {
    int ax = alignedX(s, x, scale, align);
    SDL_Color sh{0, 0, 0, (Uint8)(color.a * 0.7f)};
    drawRaw(r, s, ax + scale, y + scale, scale, sh);
    drawRaw(r, s, ax, y, scale, color);
}

